    const busy = !!(BB.In && (BB.In.use || BB.In.act)) || (!!P.act && !sitting);
    if (moving || busy) {
      idle.t = 0; idle.next = 0; idle.activeT += dt;
      if (idle.activeT > 25) { idle.activeT = 0; if (LAD.idle > 0) LAD.idle--; idle.fires = 0; }
      return;
    }
    /* progress detection (cheap: twice a second) */
    idle.scoreT += dt;
    if (idle.scoreT > 0.5) {
      idle.scoreT = 0;
      try {
        const p = BB.tasks && BB.tasks.progress ? BB.tasks.progress(S) : null;
        if (p) {
          if (idle.lastScore != null && p.score > idle.lastScore + 0.4) { LAD.idle = 0; idle.fires = 0; idle.t = 0; idle.next = 0; }
          idle.lastScore = p.score;
        }
      } catch (e) { /* tasks not ready */ }
    }
    const near = !!(BB.cur && BB.cur.hot && BB.cur.prompt);
    const base = (near ? 8 : 15) * (sitting ? 0.6 : 1);
    if (!idle.next) idle.next = base;
    idle.t += dt;
    if (idle.t < idle.next) return;
    const ctx = { S, near: near ? BB.cur.hot : null, sitting };
    let r;
    if (near || sitting || idle.fires >= 2) r = dlg.escalate('idle', ctx);
    else r = bark('idle', ctx);
