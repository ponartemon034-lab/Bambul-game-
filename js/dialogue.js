  function meta(cat) {
    const m = META[cat] || {};
    let prio = m.prio;
    if (prio == null) {
      if (/:(done|success|tested|flush|rotten)$/.test(cat) || /^tool:/.test(cat)) prio = P_DONE;
      else if (/^roomEnter/.test(cat)) prio = P_FLAVOUR;
      else prio = P_INTER;
    }
    return { prio, cd: m.cd != null ? m.cd : CDEF, who: m.who || 'bamboul' };
  }
  dlg._meta = meta;

  /* ------------------------------------------------------------ bark director */
  const GCD = 2.4;                                                   // global cooldown between barks (game s)
  let cur = null;                                                    // {prio, until}
  let lastShown = null;                                              // {cat,text,prio,t}
  const queue = [];                                                  // pending {text,who,prio,dur,exp,cat}
  dlg.last = null;

  function durOf(text) { return clamp(1.7 + text.length * 0.052, 2.4, 7.5); }
  function display(text, who, prio, dur, cat) {
    const t = now();
    cur = { prio, until: t + dur * 0.92 };
    lastShown = dlg.last = { cat, text, who, prio, t };
    try { if (BB.ui && BB.ui.say) BB.ui.say(text, { who, dur, prio }); } catch (e) { /* ui may be mid-init */ }
  }
  function uiBusy() { try { return !!(BB.ui && BB.ui.busy && BB.ui.busy()); } catch (e) { return false; } }

  function bark(cat, ctx, opts) {
    opts = opts || {};
    if (!POOL[cat]) return null;
    const m = meta(cat);
    const prio = opts.prio != null ? opts.prio : m.prio;
    const who = opts.who || m.who;
    const t = now();
    const force = !!opts.force;
    const curBlocked = !force && !!cur && t < cur.until && prio < cur.prio;
    if (!force) {
      if (prio <= P_FLAVOUR && uiBusy()) return null;
      if (CD[cat] != null && t - CD[cat] < m.cd) return null;
      if (curBlocked) { if (prio < P_INTER) return null; }          // low priority never queues behind a higher bark
      else if (lastShown && t - lastShown.t < GCD && prio <= lastShown.prio) return null;
    }
    const blocked = curBlocked;
    const text = line(cat, ctx);
    if (!text) return null;
    CD[cat] = t;
    const dur = opts.dur || durOf(text);
    if (blocked) {                                                  // keep important lines, drop stale ones
      queue.push({ text, who, prio, dur, exp: t + 6, cat });
      if (queue.length > 2) { queue.sort((a, b) => b.prio - a.prio); queue.length = 2; }
      return text;
    }
    display(text, who, prio, dur, cat);
    return text;
  }
  dlg.bark = bark;

  function pump() {
    if (!queue.length) return;
    const t = now();
    for (let i = queue.length - 1; i >= 0; i--) if (queue[i].exp < t) queue.splice(i, 1);
    if (!queue.length || (cur && t < cur.until)) return;
    queue.sort((a, b) => b.prio - a.prio);
    const q = queue.shift();
    display(q.text, q.who, q.prio, q.dur, q.cat);
  }
  dlg.queueLength = () => queue.length;

